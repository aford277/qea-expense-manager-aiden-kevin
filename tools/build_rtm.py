"""Build the automated-test side of the RTM from the "Covers:" lines in the test code.

Python: the docstring of each test_* function in employee-app-python/tests/
Java:   the @DisplayName("Covers: ...") of each test method in manager-app-java/src/test/java/

Writes docs/rtm-automated.md and lists gaps: a Must requirement with no test,
a test with no Covers line, or a Covers line naming a requirement that doesn't exist.
Run from the repo root: python tools/build_rtm.py   (exit code 1 = gaps found)
"""

import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PY_APP = ROOT / "employee-app-python"
JAVA_TESTS = ROOT / "manager-app-java" / "src" / "test" / "java"

REQUIREMENTS = ([f"FR-A{i}" for i in range(1, 5)] + [f"FR-E{i}" for i in range(1, 6)]
                + [f"FR-M{i}" for i in range(1, 5)] + [f"FR-S{i}" for i in range(1, 6)]
                + [f"VR-0{i}" for i in range(1, 10)])
NOT_MUST = {"FR-M4"} | {r for r in REQUIREMENTS if r.startswith("VR-")}


def ids_on_covers_line(text):
    """Requirement IDs after 'Covers:', before the ' - ' description. Brackets like (TA-01) are skipped."""
    match = re.search(r"Covers:\s*(.*)", text or "")
    if not match:
        return None
    ids_part = re.sub(r"\(.*?\)", "", re.split(r"\s[-–]\s", match.group(1))[0])
    return re.findall(r"\b(?:FR|VR)-[A-Z]*\d+\b", ids_part)


def python_tests():
    for path in sorted((PY_APP / "tests").rglob("test_*.py")):
        for node in ast.walk(ast.parse(path.read_text(encoding="utf-8"))):
            if isinstance(node, ast.FunctionDef) and node.name.startswith("test_"):
                name = f"{path.relative_to(PY_APP).as_posix()}::{node.name}"
                yield name, ids_on_covers_line(ast.get_docstring(node))


def java_tests():
    for path in sorted(JAVA_TESTS.rglob("*.java")):
        # drop comments, so example code inside a comment isn't read as a test
        source = re.sub(r"/\*.*?\*/|//[^\n]*", "", path.read_text(encoding="utf-8"), flags=re.DOTALL)
        start = 0
        for method in re.finditer(r"\bvoid\s+(\w+)\s*\(", source):
            annotations, start = source[start:method.start()], method.end()
            if "@Test" in annotations or "@ParameterizedTest" in annotations:
                display = re.search(r'@DisplayName\("(.*?)"\)', annotations)
                yield f"{path.stem}#{method.group(1)}", ids_on_covers_line(display and display.group(1))


tests_for = {req: [] for req in REQUIREMENTS}
no_covers, unknown = [], []
for name, ids in [*python_tests(), *java_tests()]:
    if not ids:
        no_covers.append(name)
    for req in ids or []:
        if req in tests_for:
            tests_for[req].append(name)
        else:
            unknown.append((name, req))

no_test = [r for r in REQUIREMENTS if r not in NOT_MUST and not tests_for[r]]
lines = ["# RTM: automated tests", "", "_Generated by `tools/build_rtm.py`. Rerun it instead of editing._", "",
         "| Requirement | Automated tests |", "|---|---|"]
lines += [f"| {r} | {'<br>'.join(f'`{t}`' for t in tests_for[r]) or '—'} |" for r in REQUIREMENTS]
lines += ["", "## Gaps", "",
          f"- Must requirements with no automated test: {', '.join(no_test) or 'none'}",
          f"- Tests with no Covers line: {', '.join(f'`{t}`' for t in no_covers) or 'none'}",
          f"- Unknown requirement IDs: {', '.join(f'`{t}` ({r})' for t, r in unknown) or 'none'}"]
(ROOT / "docs").mkdir(exist_ok=True)
(ROOT / "docs" / "rtm-automated.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

print("\n".join(lines[-3:]))
sys.exit(1 if no_test or no_covers or unknown else 0)